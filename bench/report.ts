import type { Thresholds } from "../src/profiles.js";
import type { TypeRow } from "./evaluate.js";
import type { Scores } from "./metrics.js";

export interface BenchmarkResults {
	readonly corpus: {
		readonly documents: Record<string, number>;
		readonly phrases: number;
		readonly units: Record<string, number>;
		readonly pairs: number;
		readonly faithful: number;
		readonly unfaithful: number;
		readonly discarded: number;
		readonly split: { readonly calibration: number; readonly test: number };
	};
	readonly objective: {
		readonly description: string;
		readonly cappedTypes: readonly string[];
		readonly maxFalseAlarm: number;
	};
	readonly thresholds: {
		readonly handSet: Record<"short" | "normal", Thresholds>;
		readonly calibrated: Record<"short" | "normal", Thresholds>;
		readonly calibrationF1: Record<"short" | "normal", number>;
		readonly plateaus: Record<
			"short" | "normal",
			Record<keyof Thresholds, { lenient: number; strict: number }>
		>;
	};
	readonly results: Record<"handSet" | "calibrated" | "strict", ResultSet>;
}

export interface ResultSet {
	readonly calibration: Scores;
	readonly test: Scores;
	readonly testByProfile: Partial<Record<string, Scores>>;
	readonly testByType: readonly TypeRow[];
}

const pct = (value: number) => `${(value * 100).toFixed(1)}%`;
const limit = (value: number) => (Number.isFinite(value) ? String(value) : "off");
const ratio = (value: number) => (value === 0 ? "off" : value.toFixed(2));

/** The README section, regenerated by `pnpm bench`. */
export function benchmarkMarkdown(results: BenchmarkResults): string {
	const { corpus, thresholds } = results;
	const hand = results.results.handSet;
	const cal = results.results.calibrated;
	const strict = results.results.strict;
	const lines: string[] = [];
	const row = (label: string, set: ResultSet) =>
		`| ${label} | ${pct(set.test.precision)} | ${pct(set.test.recall)} | ${set.test.f1.toFixed(3)} | ${pct(set.test.falsePositiveRate)} |`;

	lines.push(
		`Held-out half: **${cal.test.n} labeled pairs** (${corpus.pairs} in total: ${corpus.unfaithful} unfaithful, ${corpus.faithful} faithful) generated from ${corpus.documents.story} stories, ${corpus.documents.fable} fables, ${corpus.documents.notice} notices and ${corpus.phrases} short phrases. "Positive" means unfaithful.`,
		"",
		"| Thresholds | Precision | Recall | F1 | False-alarm rate |",
		"| --- | ---: | ---: | ---: | ---: |",
		row("Hand-set (original 0.78 / 0.82 / 0.90)", hand),
		row("**Calibrated (default)**", cal),
		row("Strict variant (`maxMovedRun: 0`)", strict),
		"",
		"**By length profile** (held-out half, calibrated default)",
		"",
		"| Profile | Pairs | Precision | Recall | F1 | Hand-set F1 |",
		"| --- | ---: | ---: | ---: | ---: | ---: |",
	);
	for (const name of ["very_short", "short", "normal"]) {
		const calibrated = cal.testByProfile[name];
		const handSet = hand.testByProfile[name];
		if (!calibrated || !handSet) continue;
		lines.push(
			`| ${name} | ${calibrated.n} | ${pct(calibrated.precision)} | ${pct(calibrated.recall)} | ${calibrated.f1.toFixed(3)} | ${handSet.f1.toFixed(3)} |`,
		);
	}

	lines.push(
		"",
		"**By perturbation type** (held-out half). Share of pairs flagged: recall for unfaithful rows, false-alarm rate for faithful rows.",
		"",
		"| Perturbation | Label | Pairs | Hand-set | Calibrated | Strict | Checks that fired (calibrated) |",
		"| --- | --- | ---: | ---: | ---: | ---: | --- |",
	);
	cal.testByType.forEach((typeRow, index) => {
		const handRow = hand.testByType[index] as TypeRow;
		const strictRow = strict.testByType[index] as TypeRow;
		const fired = Object.entries(typeRow.caughtBy)
			.slice(0, 3)
			.map(([code, count]) => `${code.replaceAll("_", " ")} (${count})`)
			.join(", ");
		lines.push(
			`| ${typeRow.description} | ${typeRow.label} | ${typeRow.n} | ${pct(handRow.flaggedRate)} | ${pct(typeRow.flaggedRate)} | ${pct(strictRow.flaggedRate)} | ${fired || "none"} |`,
		);
	});

	lines.push(
		"",
		"**Confusion matrix** (held-out half, calibrated default)",
		"",
		"| | Flagged | Passed |",
		"| --- | ---: | ---: |",
		`| Unfaithful | ${cal.test.tp} (true positive) | ${cal.test.fn} (missed) |`,
		`| Faithful | ${cal.test.fp} (false alarm) | ${cal.test.tn} (true negative) |`,
		"",
		`**Operating points.** Chosen to maximize ${results.objective.description}, with each surface-only edit (${results.objective.cappedTypes.map((type) => type.replaceAll("_", " ")).join(", ")}) kept under a ${pct(results.objective.maxFalseAlarm)} false-alarm rate. Ratios are minimums, runs are maximums in content-word spans. **Bold** values decided the calibration; _italic_ values are guards, set at the strictest value that caused no false alarm on the calibration half; \`off\` means any value would have cost accuracy.`,
		"",
		"| Profile | Ordered | Lexical | Order retention | Ending | Max dropped run | Max moved run | Calibration score |",
		"| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
	);
	for (const name of ["short", "normal"] as const) {
		const hand = thresholds.handSet[name];
		lines.push(
			`| ${name} (hand-set) | ${ratio(hand.ordered)} | ${ratio(hand.lexical)} | ${ratio(hand.orderRetention)} | ${ratio(hand.payoff)} | ${limit(hand.maxMissingRun)} | ${limit(hand.maxMovedRun)} | |`,
		);
		const chosen = thresholds.calibrated[name];
		const plateau = thresholds.plateaus[name];
		const cell = (key: keyof Thresholds, text: string) => {
			if (text === "off") return text;
			const range = plateau[key];
			const guard = key.startsWith("max") ? range.lenient === Number.POSITIVE_INFINITY : range.lenient === 0;
			return guard ? `_${text}_` : `**${text}**`;
		};
		lines.push(
			`| ${name} (calibrated) | ${cell("ordered", ratio(chosen.ordered))} | ${cell("lexical", ratio(chosen.lexical))} | ${cell("orderRetention", ratio(chosen.orderRetention))} | ${cell("payoff", ratio(chosen.payoff))} | ${cell("maxMissingRun", limit(chosen.maxMissingRun))} | ${cell("maxMovedRun", limit(chosen.maxMovedRun))} | ${thresholds.calibrationF1[name].toFixed(3)} |`,
		);
	}
	lines.push("| very_short (fixed) | 1.00 | 1.00 | 1.00 | 1.00 | 0 | 0 | |");
	return lines.join("\n");
}
